"""Command line: search, show a document, export the manifest, ingest norms.

  python3 -m neko_legal_kb.cli search "oferta publica de tokens" [-k 5] [--topic obligations] [--json]
  python3 -m neko_legal_kb.cli show <doc-id>
  python3 -m neko_legal_kb.cli list
  python3 -m neko_legal_kb.cli export        # writes data/index.json and data/chunks.jsonl

Legal texts (laws/):
  python3 -m neko_legal_kb.cli norms                       # registry and what is stored
  python3 -m neko_legal_kb.cli ingest ley-7732 [--file saved.html|.pdf] [--url URL] [--force] [--refresh]
  python3 -m neko_legal_kb.cli article ley-7732 1
  python3 -m neko_legal_kb.cli law "activos virtuales" [--area antilavado] [--norm ley-7786]
"""

import argparse
import json
import sys

from .corpus import REPO_ROOT, chunks_of
from . import laws
from .search import KnowledgeBase, format_hits, format_units


def export(kb, out=REPO_ROOT / "data"):
    out.mkdir(exist_ok=True)
    manifest = {
        "name": "neko-legal-kb",
        "description": "Legal knowledge base for tokenizing real-world assets with Neko",
        "documents": [d.summary() for d in kb.docs.values()],
    }
    (out / "index.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    with open(out / "chunks.jsonl", "w", encoding="utf-8") as f:
        for d in kb.docs.values():
            for c in chunks_of(d):
                row = {**c.__dict__, "as_of": d.as_of, "status": d.status, "verified": d.verified, "sources": d.sources}
                f.write(json.dumps(row, ensure_ascii=False) + "\n")
    (REPO_ROOT / "llms.txt").write_text(llms_txt(kb), encoding="utf-8")
    return out


def llms_txt(kb):
    """llms.txt (https://llmstxt.org): a Markdown map of the repo for LLMs."""
    lines = [
        "# neko-legal-kb",
        "",
        "> Legal knowledge base for tokenizing real-world assets with Neko: securities and public offering,"
        " AML/VASP, personal data, US offering exemptions, and reference norms. Every section cites its sources.",
        "",
        "Generated by `neko_legal_kb.cli export`; do not edit by hand.",
        "",
    ]
    for topic in kb.topics():
        lines += [f"## {topic}", ""]
        for d in kb.docs.values():
            if d.topic == topic:
                lines.append(f"- [{d.title}]({d.path}): as of {d.as_of}, {d.status}, backed by {d.verified}")
        lines.append("")
    if kb.norms:
        lines += ["## Legal texts (verbatim, article level)", ""]
        for n in kb.norms.values():
            lines.append(
                f"- [{n['title']}](laws/{n['id']}/text.md): {n['units']} units, version {n['version_date'] or 'unknown'},"
                f" retrieved {n['retrieved_at']}"
            )
        lines.append("")
    return "\n".join(lines)


def run_eval(kb, k=3):
    """Document-level (eval/questions.json) and section-level (eval/sections.json) hit rates.

    Skips gracefully when eval files are not present."""
    eval_dir = REPO_ROOT / "eval"
    total_hits = total = 0
    ran = False
    for name, key in (("questions.json", "doc_id"), ("sections.json", "chunk_id")):
        path = eval_dir / name
        if not path.exists():
            print(f"{name}: skipped (missing {path})")
            continue
        ran = True
        qs = json.loads(path.read_text(encoding="utf-8"))
        hits = 0
        for item in qs:
            got = [h[key] for h in kb.search(item["q"], k)]
            ok = item["expect"] in got
            hits += ok
            if not ok:
                print(f"MISS [{name}] {item['q']} -> expected {item['expect']}, got {got}")
        print(f"{name}: top-{k} hit rate {hits}/{len(qs)}")
        total_hits, total = total_hits + hits, total + len(qs)
    if not ran:
        print("eval: no eval files found; nothing to run")
        return 0, 0
    return total_hits, total


def run_ingest(a):
    if a.file and len(a.norm_ids) > 1:
        sys.exit("--file takes one norm id")
    failed = 0
    for norm_id in a.norm_ids:
        try:
            path, units, problems = laws.ingest(
                norm_id, file=a.file, url=a.url, force=a.force, refresh=a.refresh
            )
        except Exception as e:  # keep going with the next norm
            failed += 1
            print(f"FAIL {norm_id}: {e}", file=sys.stderr)
            continue
        print(f"OK   {norm_id}: {len(units)} units -> {path}")
        for p in problems:
            print(f"     warning: {p}")
    if failed:
        sys.exit(1)


def main(argv=None):
    ap = argparse.ArgumentParser(prog="neko-legal-kb")
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("search")
    s.add_argument("query")
    s.add_argument("-k", type=int, default=5)
    s.add_argument("--topic")
    s.add_argument("--json", action="store_true")
    sh = sub.add_parser("show")
    sh.add_argument("doc_id")
    sub.add_parser("list")
    sub.add_parser("export")
    e = sub.add_parser("eval")
    e.add_argument("-k", type=int, default=3)
    sub.add_parser("norms")
    ing = sub.add_parser("ingest")
    ing.add_argument("norm_ids", nargs="+")
    ing.add_argument("--file", help="saved HTML, PDF or text of the norm (one norm only)")
    ing.add_argument("--url", help="source URL (recorded as provenance with --file)")
    ing.add_argument("--force", action="store_true", help="write even if the title check fails")
    ing.add_argument("--refresh", action="store_true", help="refetch from SCIJ even if cached")
    ar = sub.add_parser("article")
    ar.add_argument("norm")
    ar.add_argument("article")
    lw = sub.add_parser("law")
    lw.add_argument("query")
    lw.add_argument("-k", type=int, default=5)
    lw.add_argument("--area")
    lw.add_argument("--norm")
    a = ap.parse_args(argv)
    if a.cmd == "ingest":
        return run_ingest(a)
    kb = KnowledgeBase()
    if a.cmd == "search":
        hits = kb.search(a.query, a.k, a.topic)
        print(json.dumps(hits, ensure_ascii=False, indent=2) if a.json else format_hits(hits))
    elif a.cmd == "show":
        d = kb.docs.get(a.doc_id)
        if not d:
            sys.exit(f"Unknown document: {a.doc_id}")
        print(d.body)
    elif a.cmd == "list":
        for d in kb.docs.values():
            print(f"{d.id:32} {d.topic:14} {d.verified:10} {d.title}")
    elif a.cmd == "norms":
        for r in laws.load_registry():
            n = kb.norms.get(r["id"])
            state = f"{n['units']} units, version {n['version_date'] or '?'}" if n else f"not ingested (phase {r['phase']})"
            print(f"{r['id']:36} {r['area']:14} {state:34} {r['title']}")
    elif a.cmd == "article":
        u = kb.get_unit(a.norm, a.article)
        if not u:
            sys.exit(f"Not found: {a.norm} {a.article}")
        print(format_units([u.__dict__]))
    elif a.cmd == "law":
        print(format_units(kb.search_law(a.query, a.k, a.area, a.norm), a.query, kb.coverage_warnings(a.query, a.area)))
    elif a.cmd == "export":
        print(f"Wrote {export(kb)}")
    else:
        hits, total = run_eval(kb, a.k)
        sys.exit(0 if hits == total else 1)


if __name__ == "__main__":
    main()
